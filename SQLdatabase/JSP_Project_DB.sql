CREATE TABLE member (
    admin_no        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,        -- 관리자 번호
    admin_name      VARCHAR2(50) NOT NULL,                                      -- 관리자 이름
    id              VARCHAR2(30) NOT NULL UNIQUE,                               -- 관리자 로그인 아이디
    password        VARCHAR2(50) NOT NULL,                                      -- 비밀번호
    role            VARCHAR2(30) DEFAULT 'ADMIN'                                -- 권한
);

CREATE TABLE report (
    report_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,        -- 게시물 ID 기본키
    user_name       VARCHAR2(20) NOT NULL,                                      -- 작성자 이름 (일반유저)
    title           VARCHAR2(200) NOT NULL,                                     -- 제목
    waste_type      VARCHAR2(50) NOT NULL,                                      -- 쓰레기 유형
    latitude        VARCHAR2(10) NOT NULL,                                      -- 위도
    longitude       VARCHAR2(10) NOT NULL,                                      -- 경도
    content         CLOB,                                                       -- 상세 내용
    status          VARCHAR2(30) DEFAULT '접수',                                -- 접수, 해결완료
    reg_date        DATE DEFAULT SYSDATE,                                       -- 작성 시간
    admin_no        NUMBER REFERENCES admin(admin_no)                           -- 처리를 맡은 관리자 번호 (참조키)
);


CREATE TABLE image_file (
    file_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,        -- 파일 번호 기본키
    report_id       NUMBER NOT NULL REFERENCES report(report_id) ON DELETE CASCADE,        --게시물 id를 참조  ON DELETE CASCADE: 참조하는 데이터가 사라지면 자동으로 삭제하는 명령.
    file_name       VARCHAR2(255) NOT NULL                                                  -- 파일 이름
);

